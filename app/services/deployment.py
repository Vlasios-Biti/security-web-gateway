def _acl(prefix,nid):return f"swg_{prefix}_n{int(nid)}"


def generate_config(c=None):
    own=c is None
    c=c or connect()
    try:
        nets=[dict(r) for r in c.execute("SELECT * FROM networks WHERE enabled=1 AND proxy_enabled=1 ORDER BY COALESCE(vlan_id,99999),id")]
        active_net_ids={n["id"] for n in nets}
        rules=[dict(r) for r in c.execute("SELECT * FROM rules WHERE action='ALLOW' AND status='active' AND (expires_at IS NULL OR expires_at='' OR julianday(expires_at)>julianday('now')) ORDER BY management_type,rule_type,destination")]
        scopes={r["id"]:sorted(effective_network_ids_for_rule(c,r["id"],r.get("scope_mode") or "selected") & active_net_ids) for r in rules}
    finally:
        if own:c.close()
    buckets={n["id"]:{"dh":[],"ds":[],"ih":[],"is":[]} for n in nets}
    for r in rules:
        val=squid_domain_token(r["destination"]) if r["rule_type"]=="domain" else r["destination"]
        for nid in scopes.get(r["id"],[]):
            if nid not in buckets:continue
            if r["rule_type"]=="domain":
                if r["protocol"] in("HTTP","BOTH"):buckets[nid]["dh"].append(val)
                if r["protocol"] in("HTTPS","BOTH"):buckets[nid]["ds"].append(val)
            else:
                if r["protocol"] in("HTTP","BOTH"):buckets[nid]["ih"].append(val)
                if r["protocol"] in("HTTPS","BOTH"):buckets[nid]["is"].append(val)
    lines=["# ============================================================",f"# GENERATED BY SECURITY WEB GATEWAY MANAGER v{APP_VERSION}","# DO NOT EDIT. GUI/database are the source of truth.","# Policy model: DEFAULT DENY + EXPLICIT ALLOW + APPLICATION/POLICY GROUP INHERITANCE.","# ============================================================","","acl swg_diag src 127.0.0.1/32","acl swg_diag src ::1",f"acl swg_diag src {PROXY_IP}/32"]
    for n in nets:
        label=f"VLAN {n['vlan_id']}" if n.get("vlan_id") else n["name"]
        lines.append(f"# Network {n['id']}: {label} | {n['cidr']}");lines.append(f'acl {_acl("net",n["id"])} src {n["cidr"]}')
    lines.append("")
    mapping=(("dh","dom_http","dstdomain"),("ds","dom_https","dstdomain"),("ih","ip_http","dst"),("is","ip_https","dst"))
    for n in nets:
        for key,name,typ in mapping:
            for val in sorted(set(buckets[n["id"]][key])):lines.append(f'acl {_acl(name,n["id"])} {typ} {val}')
    lines.append("")
    agg={k:sorted({x for b in buckets.values() for x in b[k]}) for k in("dh","ds","ih","is")}
    for val in agg["dh"]:lines.append(f"acl swg_diag_dom_http dstdomain {val}")
    for val in agg["ds"]:lines.append(f"acl swg_diag_dom_https dstdomain {val}")
    for val in agg["ih"]:lines.append(f"acl swg_diag_ip_http dst {val}")
    for val in agg["is"]:lines.append(f"acl swg_diag_ip_https dst {val}")
    lines.append("")
    for n in nets:
        nid=n["id"];net=_acl("net",nid);b=buckets[nid]
        if b["ds"]:lines.append(f"http_access allow {net} CONNECT port_https {_acl('dom_https',nid)}")
        if b["is"]:lines.append(f"http_access allow {net} CONNECT port_https {_acl('ip_https',nid)}")
        if b["dh"]:lines.append(f"http_access allow {net} port_http {_acl('dom_http',nid)}")
        if b["ih"]:lines.append(f"http_access allow {net} port_http {_acl('ip_http',nid)}")
    if agg["ds"]:lines.append("http_access allow swg_diag CONNECT port_https swg_diag_dom_https")
    if agg["is"]:lines.append("http_access allow swg_diag CONNECT port_https swg_diag_ip_https")
    if agg["dh"]:lines.append("http_access allow swg_diag port_http swg_diag_dom_http")
    if agg["ih"]:lines.append("http_access allow swg_diag port_http swg_diag_ip_http")
    return "\n".join(lines)+"\n"


def current_live():
    try:return LIVE_MANAGED_CONF.read_text(encoding="utf-8")
    except Exception:return ""


def preview_diff():
    return "".join(difflib.unified_diff(current_live().splitlines(True),generate_config().splitlines(True),fromfile="production",tofile="candidate"))


def _effective_policy_text(text):
    return "\n".join(line.strip() for line in (text or "").splitlines() if line.strip() and not line.lstrip().startswith("#"))


def effective_policy_changed():
    return _effective_policy_text(current_live()) != _effective_policy_text(generate_config())


def _rows(c,table):return [dict(r) for r in c.execute(f"SELECT * FROM {table} ORDER BY 1")]


def state_snapshot(c=None):
    own=c is None
    c=c or connect()
    try:
        state={
            "rules":_rows(c,"rules"),"networks":_rows(c,"networks"),"applications":_rows(c,"applications"),"policy_groups":_rows(c,"policy_groups"),
            "rule_networks":_rows(c,"rule_networks"),"application_rules":_rows(c,"application_rules"),"application_networks":_rows(c,"application_networks"),
            "policy_group_applications":_rows(c,"policy_group_applications"),"policy_group_rules":_rows(c,"policy_group_rules"),"policy_group_networks":_rows(c,"policy_group_networks")
        }
        return json.dumps(state,separators=(",",":"))
    finally:
        if own:c.close()


def helper_request(action,**payload):
    if MODE!="production":raise RuntimeError("Privileged operations are disabled in candidate preview mode.")
    s=socket.socket(socket.AF_UNIX,socket.SOCK_STREAM);s.settimeout(40)
    try:
        s.connect(DEPLOY_SOCKET);body={"action":action};body.update(payload);s.sendall((json.dumps(body)+"\n").encode());s.shutdown(socket.SHUT_WR);data=b""
        while True:
            x=s.recv(4096)
            if not x:break
            data+=x
        if not data:raise RuntimeError("Empty response from privileged helper.")
        return json.loads(data)
    finally:s.close()


@contextmanager
def deployment_lock():
    CANDIDATE_ROOT.parent.mkdir(parents=True,exist_ok=True)
    with (CANDIDATE_ROOT.parent/'deployment.lock').open('a+') as stream:
        fcntl.flock(stream.fileno(),fcntl.LOCK_EX)
        try:yield
        finally:fcntl.flock(stream.fileno(),fcntl.LOCK_UN)


def _publish_snapshot(content,state,actor,source_ip,description,expected_base=None):
    live=current_live()
    diff=''.join(difflib.unified_diff(live.splitlines(True),content.splitlines(True),fromfile='production',tofile='candidate'))
    cid=str(uuid.uuid4());d=CANDIDATE_ROOT/cid;d.mkdir(parents=True,exist_ok=False)
    (d/'security-web-gateway.conf').write_text(content,encoding='utf-8')
    digest=hashlib.sha256(content.encode()).hexdigest()
    (d/'manifest.json').write_text(json.dumps({'sha256':digest,'base_sha256':expected_base if expected_base is not None else hashlib.sha256(live.encode()).hexdigest()}))
    result=helper_request('deploy',candidate_id=cid)
    c=connect()
    try:
        c.execute('BEGIN IMMEDIATE')
        previous=c.execute("SELECT id FROM deployments WHERE status='deployed' ORDER BY id DESC LIMIT 1").fetchone()
        number=c.execute('SELECT COUNT(*) FROM deployments').fetchone()[0]+1
        status='deployed' if result.get('ok') else 'failed'
        recorded=copy.deepcopy(state)
        if result.get('ok'):
            unchanged=json.loads(state_snapshot(c))==state
            # Include relationship tables: linking an existing shared rule can
            # change policy without changing the parent's second-resolution timestamp.
            if unchanged:
                for table in ('rules','networks','applications','policy_groups'):
                    for row in state.get(table,[]):
                        c.execute(f'UPDATE {table} SET pending=0 WHERE id=?',(row['id'],))
            else:result={**result,'pending_changes_retained':True}
            for table in ('rules','networks','applications','policy_groups'):
                for row in recorded.get(table,[]):row['pending']=0
        cur=c.execute("""INSERT INTO deployments(version,status,created_by,description,config_sha256,config_content,diff_text,state_json,previous_deployment_id,deployed_at)
          VALUES(?,?,?,?,?,?,?,?,?,CASE WHEN ?='deployed' THEN CURRENT_TIMESTAMP ELSE NULL END)""",
          (f'v{number:04d}',status,actor,description,digest,content,diff,json.dumps(recorded,separators=(',',':')),previous['id'] if previous else None,status))
        c.commit()
        audit(actor,'DEPLOY','SUCCESS' if result.get('ok') else 'FAILED','deployment',cur.lastrowid,source_ip,json.dumps(result))
    except Exception:c.rollback();raise
    finally:c.close()
    return result


def deploy(actor,source_ip,description=''):
    if MODE!='production':raise RuntimeError('Deployment is disabled in candidate preview mode.')
    with deployment_lock():
        c=connect()
        try:
            c.execute('BEGIN')
            expected_base=hashlib.sha256(current_live().encode()).hexdigest()
            content=generate_config(c)
            state=json.loads(state_snapshot(c))
            c.commit()
        finally:c.close()
        return _publish_snapshot(content,state,actor,source_ip,description,expected_base)


def _insert_rows(c,table,rows):
    if not rows:return
    cols=list(rows[0].keys());sql=f"INSERT INTO {table}({','.join(cols)}) VALUES({','.join('?' for _ in cols)})"
    for row in rows:c.execute(sql,[row.get(k) for k in cols])


def rollback_to(deployment_id,actor,source_ip):
    c=connect();dep=None
    try:
        dep=c.execute("SELECT * FROM deployments WHERE id=? AND status='deployed'",(deployment_id,)).fetchone()
        if not dep:raise ValueError("Deployment not found.")
        state=json.loads(dep["state_json"])
        if "applications" not in state:raise ValueError("This legacy snapshot predates the application-policy model and cannot be rolled back automatically from this release.")
        c.execute("BEGIN IMMEDIATE")
        c.execute("UPDATE application_learning_sessions SET status='stopped' WHERE status='active'")
        for t in("policy_group_networks","policy_group_rules","policy_group_applications","application_networks","application_rules","rule_networks","policy_groups","applications","rules","networks"):c.execute(f"DELETE FROM {t}")
        _insert_rows(c,"networks",state.get("networks",[]));_insert_rows(c,"rules",state.get("rules",[]));_insert_rows(c,"applications",state.get("applications",[]));_insert_rows(c,"policy_groups",state.get("policy_groups",[]))
        for t in("rule_networks","application_rules","application_networks","policy_group_applications","policy_group_rules","policy_group_networks"):_insert_rows(c,t,state.get(t,[]))
        c.commit()
    except Exception:c.rollback();raise
    finally:c.close()
    return deploy(actor,source_ip,f"Rollback to {dep['version']}")


def drift_status():
    live=current_live();dig=hashlib.sha256(live.encode()).hexdigest() if live else None;c=connect()
    try:r=c.execute("SELECT version,config_sha256,deployed_at FROM deployments WHERE status='deployed' ORDER BY id DESC LIMIT 1").fetchone()
    finally:c.close()
    if not r:return {"state":"unknown","live_sha":dig,"expected_sha":None,"version":None,"message":"No trusted deployment baseline yet."}
    clean=bool(dig and dig==r["config_sha256"]);return {"state":"clean" if clean else "drift","live_sha":dig,"expected_sha":r["config_sha256"],"version":r["version"],"deployed_at":r["deployed_at"],"message":"Live managed policy matches the last successful deployment." if clean else "Live managed policy differs from the last successful deployment."}


def reconcile_pending_if_no_diff():
    """Clear stale pending flags only when effective Squid directives are identical.

    Release/version comments are ignored; ACL/http_access directives are not.
    """
    live=_effective_policy_text(current_live());candidate=_effective_policy_text(generate_config())
    if live!=candidate:
        diff="".join(difflib.unified_diff(live.splitlines(True),candidate.splitlines(True),fromfile="production-effective",tofile="candidate-effective"))
        return {"cleared":False,"reason":"effective policy diff exists","diff_lines":len(diff.splitlines())}
    c=connect()
    try:
        counts={
            "rules":c.execute("SELECT COUNT(*) c FROM rules WHERE pending=1").fetchone()["c"],
            "networks":c.execute("SELECT COUNT(*) c FROM networks WHERE pending=1").fetchone()["c"],
            "applications":c.execute("SELECT COUNT(*) c FROM applications WHERE pending=1").fetchone()["c"],
            "policy_groups":c.execute("SELECT COUNT(*) c FROM policy_groups WHERE pending=1").fetchone()["c"],
        }
        c.execute("UPDATE rules SET pending=0 WHERE pending=1")
        c.execute("UPDATE networks SET pending=0 WHERE pending=1")
        c.execute("UPDATE applications SET pending=0 WHERE pending=1")
        c.execute("UPDATE policy_groups SET pending=0 WHERE pending=1")
        c.commit()
        return {"cleared":True,"counts":counts,"reason":"no effective policy diff"}
    finally:c.close()

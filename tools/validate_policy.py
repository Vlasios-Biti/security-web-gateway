#!/usr/bin/env python3
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.services.deployment import generate_config
from app.db import verify_schema
from app.config import SQUID_CONF

PREFIX = '# LEGACY-DISABLED-BY-SECURITY-WEB-GATEWAY '

TARGET_START = re.compile(
    r'''^\s*(?:
        acl\s+(?:google_search|google_maps|business_domains)\s+dstdomain\b
      | acl\s+(?:allowed_http_ips|allowed_https_ips)\s+dst\b
      | http_access\s+allow\s+allowed_clients\s+CONNECT\s+port_https\s+(?:google_search|google_maps|business_domains|allowed_https_ips)\s*$
      | http_access\s+allow\s+allowed_clients\s+port_http\s+(?:google_search|google_maps|business_domains|allowed_http_ips)\s*$
    )''',
    re.IGNORECASE | re.VERBOSE,
)


def _continued(line: str) -> bool:
    return line.rstrip('\r\n').rstrip().endswith('\\')


def disable_legacy_statements(text: str) -> str:
    """Disable complete legacy Squid statements, including backslash continuations."""
    lines = text.splitlines(keepends=True)
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.lstrip()
        if not stripped.startswith('#') and TARGET_START.match(line):
            out.append(PREFIX + stripped)
            cont = _continued(line)
            i += 1
            while cont and i < len(lines):
                nxt = lines[i]
                if nxt.lstrip().startswith('#'):
                    out.append(nxt)
                else:
                    out.append(PREFIX + nxt.lstrip())
                cont = _continued(nxt)
                i += 1
            continue
        out.append(line)
        i += 1
    return ''.join(out)


def transformed(base: str, inc: Path) -> str:
    text = re.sub(
        r'# BEGIN SECURITY-WEB-GATEWAY-MANAGED.*?# END SECURITY-WEB-GATEWAY-MANAGED\n?',
        '', base, flags=re.S,
    )
    text = re.sub(
        r'# BEGIN HQ PROXY MANAGER MANAGED POLICY.*?# END HQ PROXY MANAGER MANAGED POLICY\n?',
        '', text, flags=re.S,
    )
    text = disable_legacy_statements(text)
    matches = list(re.finditer(r'^\s*http_access\s+deny\s+all\s*$', text, re.M))
    if not matches:
        raise RuntimeError('Final http_access deny all not found.')
    pos = matches[-1].start()
    block = (
        '# BEGIN SECURITY-WEB-GATEWAY-MANAGED\n'
        f'include {inc}\n'
        '# END SECURITY-WEB-GATEWAY-MANAGED\n\n'
    )
    return text[:pos] + block + text[pos:]


def self_test() -> None:
    sample = (
        'acl google_search dstdomain \\\n'
        '    "/etc/squid/allowlists/google-search.txt"\n'
        'acl google_maps dstdomain "/etc/squid/allowlists/google-maps.txt"\n'
        'http_access allow allowed_clients CONNECT port_https google_search\n'
        'http_access deny all\n'
    )
    x = transformed(sample, Path('/tmp/managed.conf'))
    leaked = [line for line in x.splitlines() if line.strip().startswith('"/etc/squid/allowlists/')]
    if leaked:
        raise RuntimeError(f'Legacy continuation leak detected: {leaked}')
    expected = '# LEGACY-DISABLED-BY-SECURITY-WEB-GATEWAY "/etc/squid/allowlists/google-search.txt"'
    if expected not in x:
        raise RuntimeError('Multiline legacy ACL self-test failed.')


def main():
    verify_schema()
    self_test()
    content = generate_config()
    with tempfile.TemporaryDirectory(prefix='security-web-gateway-validate-') as td_raw:
        td = Path(td_raw)
        managed = td / 'security-web-gateway.conf'
        conf = td / 'squid.conf'
        managed.write_text(content, encoding='utf-8')
        conf.write_text(
            transformed(SQUID_CONF.read_text(encoding='utf-8'), managed),
            encoding='utf-8',
        )
        p = subprocess.run(
            ['/usr/sbin/squid', '-k', 'parse', '-f', str(conf)],
            capture_output=True,
            text=True,
            check=False,
            timeout=30,
        )
        if p.returncode:
            print(p.stdout)
            print(p.stderr, file=sys.stderr)
            raise SystemExit(p.returncode)
        print('POLICY VALID')
        print(f'Generated bytes: {len(content.encode())}')


if __name__ == '__main__':
    main()
